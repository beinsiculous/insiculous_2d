#!/usr/bin/env python3
"""Write `sine.sf2`: the smallest SoundFont 2 that a synthesizer test can reason about.

One sample (an A4 sine, 440 Hz, recorded at 44000 Hz so one cycle is exactly 100
sample points and the loop is seamless), one instrument that loops it for as long as the
key is held and releases over 0.1 s, one preset (bank 0, program 0) that plays the
instrument across the whole keyboard. No modulators, no velocity layers, no key zones:
a rendered note is a plain sine at the played pitch, so a test can count zero crossings
and measure RMS without knowing anything about a real bank.

Standard library only, and byte-reproducible: run it twice and `cmp` the outputs.

Usage: scripts/make_sine_soundfont.py [output_path]
       (default: crates/music_midi/fixtures/sine.sf2)
"""
import math
import os
import struct
import sys

SAMPLE_RATE = 44000
ROOT_KEY = 69
POINTS_PER_CYCLE = 100
CYCLE_COUNT = 44
AMPLITUDE = 0.5
RELEASE_SECONDS = 0.1
# The SoundFont 2.01 specification asks for at least 46 zero points after every sample,
# so an interpolating reader never runs into the next sample's data.
TRAILING_ZERO_POINTS = 46

GENERATOR_INSTRUMENT = 41
GENERATOR_RELEASE_VOLUME_ENVELOPE = 38
GENERATOR_SAMPLE_MODES = 54
GENERATOR_SAMPLE_ID = 53
SAMPLE_MODE_LOOP_CONTINUOUSLY = 1
SAMPLE_TYPE_MONO = 1


def chunk(identifier, payload):
    padding = b"\0" if len(payload) % 2 else b""
    return identifier + struct.pack("<I", len(payload)) + payload + padding


def list_chunk(list_type, chunks):
    return chunk(b"LIST", list_type + b"".join(chunks))


def fixed_name(text):
    return text.encode("ascii").ljust(20, b"\0")


def zero_terminated(text):
    encoded = text.encode("ascii") + b"\0"
    return encoded + (b"\0" if len(encoded) % 2 else b"")


def timecents(seconds):
    return round(1200 * math.log2(seconds))


def sample_points():
    point_count = POINTS_PER_CYCLE * CYCLE_COUNT
    points = [round(math.sin(2 * math.pi * index / POINTS_PER_CYCLE) * AMPLITUDE * 32767)
              for index in range(point_count)]
    return points + [0] * TRAILING_ZERO_POINTS, point_count


def generator(operator, amount):
    return struct.pack("<Hh", operator, amount)


def soundfont_bytes():
    points, point_count = sample_points()
    info = list_chunk(b"INFO", [
        chunk(b"ifil", struct.pack("<HH", 2, 1)),
        chunk(b"isng", zero_terminated("EMU8000")),
        chunk(b"INAM", zero_terminated("Insiculous sine fixture")),
        chunk(b"ICOP", zero_terminated("Public domain; generated by scripts/make_sine_soundfont.py")),
    ])
    sample_data = list_chunk(b"sdta", [
        chunk(b"smpl", struct.pack(f"<{len(points)}h", *points)),
    ])

    preset_headers = (
        fixed_name("Sine") + struct.pack("<HHHIII", 0, 0, 0, 0, 0, 0)
        + fixed_name("EOP") + struct.pack("<HHHIII", 0, 0, 1, 0, 0, 0))
    preset_bags = struct.pack("<HH", 0, 0) + struct.pack("<HH", 1, 0)
    preset_modulators = b"\0" * 10
    preset_generators = generator(GENERATOR_INSTRUMENT, 0) + generator(0, 0)

    instruments = (
        fixed_name("Sine") + struct.pack("<H", 0)
        + fixed_name("EOI") + struct.pack("<H", 1))
    instrument_bags = struct.pack("<HH", 0, 0) + struct.pack("<HH", 3, 0)
    instrument_modulators = b"\0" * 10
    instrument_generators = (
        generator(GENERATOR_RELEASE_VOLUME_ENVELOPE, timecents(RELEASE_SECONDS))
        + generator(GENERATOR_SAMPLE_MODES, SAMPLE_MODE_LOOP_CONTINUOUSLY)
        + generator(GENERATOR_SAMPLE_ID, 0)
        + generator(0, 0))

    loop_start = POINTS_PER_CYCLE
    sample_headers = (
        fixed_name("Sine A4")
        + struct.pack("<IIIIIBbHH", 0, point_count, loop_start, point_count,
                      SAMPLE_RATE, ROOT_KEY, 0, 0, SAMPLE_TYPE_MONO)
        + fixed_name("EOS") + struct.pack("<IIIIIBbHH", 0, 0, 0, 0, 0, 0, 0, 0, 0))

    preset_data = list_chunk(b"pdta", [
        chunk(b"phdr", preset_headers),
        chunk(b"pbag", preset_bags),
        chunk(b"pmod", preset_modulators),
        chunk(b"pgen", preset_generators),
        chunk(b"inst", instruments),
        chunk(b"ibag", instrument_bags),
        chunk(b"imod", instrument_modulators),
        chunk(b"igen", instrument_generators),
        chunk(b"shdr", sample_headers),
    ])
    body = b"sfbk" + info + sample_data + preset_data
    return b"RIFF" + struct.pack("<I", len(body)) + body


def main():
    output_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "crates", "music_midi", "fixtures", "sine.sf2")
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "wb") as output_file:
        output_file.write(soundfont_bytes())
    print(output_path)


if __name__ == "__main__":
    main()
